/**
 * The three languages of the app. The choice is saved on the phone and switches every screen at once
 * (no restart): MainActivity provides [LocalStrings], every screen reads `LocalStrings.current`.
 * Texts that come from the server (error messages, live notices) stay in English.
 */
enum class Lang(val code: String, val label: String, val strings: Strings) {
    EN("en", "English", En),
    UZ("uz", "Oʻzbekcha", Uz),
    RU("ru", "Русский", Ru);

    companion object {
        /** "uz" -> UZ, "ru" -> RU, anything else -> English. */
        fun fromCode(code: String?): Lang = entries.firstOrNull { it.code == code } ?: EN
    }
}

val LocalStrings = staticCompositionLocalOf<Strings> { En }

